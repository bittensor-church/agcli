#[test]
#[ignore = "requires a running local chain and sudo key //Alice"]
fn green_path_admin_local_chain_set_default_take() {
    let endpoint =
        std::env::var("AGCLI_AUDIT_ENDPOINT").unwrap_or_else(|_| "ws://127.0.0.1:9944".to_string());
    let take = std::env::var("AGCLI_AUDIT_DEFAULT_TAKE").unwrap_or_else(|_| "32767".to_string());

    let output = Command::new(env!("CARGO_BIN_EXE_agcli"))
        .args([
            "--network",
            "local",
            "--endpoint",
            &endpoint,
            "--output",
            "json",
            "admin",
            "set-default-take",
            "--take",
            &take,
            "--sudo-key",
            "//Alice",
        ])
        .output()
        .expect("failed to invoke agcli");

    assert!(
        output.status.success(),
        "admin green path failed\nstdout: {}\nstderr: {}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );

    let value: serde_json::Value =
        serde_json::from_slice(&output.stdout).expect("stdout was not valid JSON");
    assert!(
        value
            .get("tx_hash")
            .and_then(|v| v.as_str())
            .map(|s| !s.is_empty())
            .unwrap_or(false),
        "expected non-empty tx_hash in output: {}",
        value
    );
}
