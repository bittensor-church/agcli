use clap::Parser;
use std::process::Command;

fn assert_parses(args: &[&str]) {
    let parsed = agcli::cli::Cli::try_parse_from(args);
    assert!(
        parsed.is_ok(),
        "failed to parse '{}': {:?}",
        args.join(" "),
        parsed.err()
    );
}

